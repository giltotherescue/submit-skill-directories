# Remove typo fix block — no longer needed

def human_name(id_: str) -> str:
    return id_.replace("-", " ").title()


def main() -> None:
    assert len(CANONICAL_IDS) == 96, len(CANONICAL_IDS)

    # Remove non-canonical yaml files
    for path in DIR.glob("*.yaml"):
        if path.name == "_template.yaml":
            continue
        if path.stem not in CANONICAL_IDS:
            path.unlink()

    for id_ in CANONICAL_IDS:
        if id_ in VERIFIED:
            data = VERIFIED[id_]
        else:
            data = stub(
                id_,
                human_name(id_),
                f"Directory manifest for {id_}.",
            )

        # Enforce splits_skills canonical rule
        if id_ in SPLITS_SKILLS_IDS:
            data["splits_skills"] = True
            data["listing_unit"] = "skill"
        else:
            if data.get("splits_skills"):
                data["splits_skills"] = False

        data["id"] = id_
        path = DIR / f"{id_}.yaml"
        with path.open("w", encoding="utf-8") as f:
            yaml.dump(data, f, sort_keys=False, allow_unicode=True, default_flow_style=False)

    count = len(list(DIR.glob("*.yaml"))) - 1  # minus template
    print(f"Wrote {count} manifests (+ _template.yaml)")


if __name__ == "__main__":
    main()
