def stub(
    id_: str,
    name: str,
    description: str,
    status: str = "wait",
    access_class: str = "web_form",
    url: str = "",
    listing_unit: str = "either",
    splits_skills: bool = False,
    notes: str = "Manifest stub — verify submission URL, access requirements, and listing_unit before setting status: active.",
    catalog_repo: str = "",
    catalog_path: str = "",
    **extra,
) -> dict:
    access: dict = {
        "class": access_class,
        "notes": notes.strip(),
    }
    if url:
        access["url"] = url
    if catalog_repo:
        access["catalog_repo"] = catalog_repo
    if catalog_path:
        access["catalog_path"] = catalog_path
    m = {
        "id": id_,
        "name": name,
        "description": description.strip(),
        "status": status,
        "access": access,
        "listing_unit": listing_unit,
        "splits_skills": splits_skills,
    }
    m.update(extra)
    return m


